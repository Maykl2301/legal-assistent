def ask_gemini(question: str, topic: str = "general") -> str | None:
    """Запит до Gemini AI якщо підключено."""
    if not gemini_available:
        return None

    topic_names = {
        "civil": "цивільне право",
        "housing": "житлові питання",
        "family": "сімейне право",
        "labor": "трудове право",
        "transport": "ДТП та транспорт",
        "credits": "кредити та борги",
        "criminal": "кримінальне право",
        "admin": "адміністративне право",
        "general": "загальні юридичні питання України",
    }
    topic_name = topic_names.get(topic, "загальні юридичні питання України")

    prompt = f"""Ти — досвідчений юрист-консультант з українського права.
Відповідай ТІЛЬКИ українською мовою.
Тема: {topic_name}
Питання: {question}

Правила:
1. Давай конкретну практичну відповідь
2. Посилайся на статті законів України (zakon.rada.gov.ua)
3. Вкажи чіткі кроки що робити
4. Максимум 200 слів
5. Без зірочок Markdown — тільки текст і емодзі
6. В кінці: рекомендація звернутись до юриста якщо ситуація серйозна"""

    try:
        response = gemini_client.models.generate_content(
            model="gemini-2.0-flash",
            contents=prompt
        )
        return response.text
    except Exception as e:
        print(f"⚠️ Помилка Gemini: {e}")
        return None


def get_legal_response(question: str, topic: str = "general") -> str:
    """
    Пошук відповіді на юридичне питання.
    1. База знань по ключових словах
    2. Gemini AI (якщо підключено)
    3. Тематична підказка
    """
    normalized_q = normalize(question)

    # 1. Пошук по ключових словах
    best_match = None
    best_score = 0

    for keywords, answer in KNOWLEDGE_BASE:
        score = sum(1 for kw in keywords if kw in normalized_q)
        if score > best_score:
            best_score = score
            best_match = answer

    if best_match and best_score > 0:
        return best_match

    # 2. Gemini AI fallback
    if gemini_available:
        print(f"🤖 Питаємо Gemini: {question[:60]}...")
        gemini_answer = ask_gemini(question, topic)
        if gemini_answer:
            return f"🤖 <b>Відповідь AI-юриста:</b>\n\n{gemini_answer}"

    # 3. Тематична підказка
    if topic in TOPIC_HINTS:
        return TOPIC_HINTS[topic]

    # 4. Загальний fallback
    return (
        "⚖️ <b>Юридична консультація</b>\n\n"
        "Уточніть своє питання — спробуйте описати ситуацію детальніше. Наприклад:\n"
        "• «Що робити якщо не платять зарплату?»\n"
        "• «Як оскаржити незаконне звільнення?»\n"
        "• «Які мої права при затриманні?»\n\n"
        "Або оберіть тему з меню нижче.\n\n"
        "📞 <b>Безоплатна правова допомога: 0 800 213 103</b>\n"
        "🌐 legalaid.gov.ua"
    )

